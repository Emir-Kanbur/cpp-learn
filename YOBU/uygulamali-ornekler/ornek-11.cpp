#include <iostream>

int main() {

    std::cout << "Merhaba, Dünya! " << std::endl;

    return 0;
 }

 /* 
 Açıklama:
 #include <iostream>: Bu satır, C++'da giriş/çıkış işlemleri için 
gerekli olan başlık dosyasını dahil eder.
 int main(): Bu satır, programın başlangıç fonksiyonunu tanımlar. 
C++ programları main fonksiyonundan çalışmaya başlar.
 std::cout << "Merhaba Dunya" << std::endl;: Bu satır, ekrana 
"Merhaba Dunya" metnini yazdırır. std::endl ise yeni bir satıra 
geçer.
 return 0;: Programın başarıyla tamamlandığını belirtmek için 0 
değerini döndürür.
*/